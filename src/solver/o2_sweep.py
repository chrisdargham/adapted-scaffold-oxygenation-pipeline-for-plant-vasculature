#!/usr/bin/env python3
r"""

Purpose
-------
Runs independent oxygen simulations for combinations of:
  - P_wall / k_eff proxy: vessel-wall oxygen transfer barrier [m/s]
  - Vmax: tissue oxygen consumption rate [mM/s]
  - inlet_mmHg: inlet oxygen concentration expressed as pO2 [mmHg]

Each run is saved in its own folder.  Each folder contains:
  - config_used.json
  - stdout.txt / stderr.txt
  - metrics.txt / metrics.csv / metrics.json
  - oxygenation_summary.csv / oxygenation_summary.json
  - oxygen_arrays/tissue_O2_mM.npy
  - oxygen_arrays/tissue_pO2_mmHg.npy
  - oxygen_arrays/lumen_O2_mM.npy
  - oxygen_arrays/lumen_pO2_mmHg.npy
  - figures generated by oxy_sim

The output root also contains:
  - MASTER_oxygenation_summary.csv
  - MASTER_failed_runs.csv

Example PowerShell
------------------
python .\src\solver\o2_sweep.py `
  --solver .\src\solver\oxy_sim_mat.py `
  --base-config .\configs\sim_configuration.json `
  --output-root .\results\sweep `
  --mode full


"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from itertools import product
from pathlib import Path
from typing import Iterable, List

import pandas as pd


def parse_float_list(text: str) -> List[float]:
    vals: List[float] = []
    for part in text.replace(";", ",").split(","):
        part = part.strip()
        if part:
            vals.append(float(part))
    if not vals:
        raise ValueError(f"Empty numeric list: {text!r}")
    return vals


def sci_label(x: float) -> str:
    """File-safe compact scientific notation."""
    s = f"{x:.0e}" if (abs(x) < 1e-2 or abs(x) >= 1e3) else f"{x:g}"
    return s.replace("+", "").replace("-", "m").replace(".", "p")


def load_json(path: Path) -> dict:
    with path.open("r", encoding="utf-8") as f:
        return json.load(f)


def write_json(path: Path, obj: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        json.dump(obj, f, indent=2)


def build_runs(args: argparse.Namespace, base: dict):
    pwall_vals = parse_float_list(args.pwall_values)
    vmax_vals = parse_float_list(args.vmax_values)
    inlet_vals = parse_float_list(args.inlet_mmhg_values)

    baseline_vmax = float(base.get("Vmax", 1e-4))
    baseline_inlet = float(base.get("inlet_mmHg", 150.0))
    baseline_pwall = float(base.get("P_wall", 3e-5))

    if args.mode == "pwall":
        combos = [(pw, baseline_vmax, baseline_inlet) for pw in pwall_vals]
    elif args.mode == "vmax":
        combos = [(baseline_pwall, vm, baseline_inlet) for vm in vmax_vals]
    elif args.mode == "inlet":
        combos = [(baseline_pwall, baseline_vmax, inn) for inn in inlet_vals]
    elif args.mode == "full":
        combos = list(product(pwall_vals, vmax_vals, inlet_vals))
    else:
        raise ValueError(f"Unknown mode: {args.mode}")

    for pwall, vmax, inlet in combos:
        run_id = f"Pw_{sci_label(pwall)}__Vmax_{sci_label(vmax)}__InO2_{sci_label(inlet)}mmHg"
        yield run_id, float(pwall), float(vmax), float(inlet)


def main() -> int:
    ap = argparse.ArgumentParser(formatter_class=argparse.ArgumentDefaultsHelpFormatter)
    ap.add_argument("--solver", type=Path, required=True, help="Path to oxy_sim_mat.py")
    ap.add_argument("--base-config", type=Path, required=True, help="Base JSON config")
    ap.add_argument("--output-root", type=Path, default=Path("batch_o2_outputs"), help="Where all batch results are saved")
    ap.add_argument("--mode", choices=["pwall", "vmax", "inlet", "full"], default="full", help="Sweep mode. Default is reduced full factorial, not the large exhaustive sweep.")
    ap.add_argument("--pwall-values", default="1e-8,1e-6,3e-5,1e-4", help="P_wall values in m/s; reduced k_eff/barrier priority levels: very low, low, baseline, high")
    ap.add_argument("--vmax-values", default="1e-5,1e-4,1e-3", help="Vmax values in mM/s; reduced consumption levels: low, baseline, high")
    ap.add_argument("--inlet-mmhg-values", default="80,150", help="Inlet pO2 values in mmHg; reduced concentration levels: moderate and air-equilibrated")
    ap.add_argument("--python", default=sys.executable, help="Python executable")
    ap.add_argument("--stop-on-fail", action="store_true", help="Stop batch after first failed run")
    args = ap.parse_args()

    base_config = load_json(args.base_config)
    output_root = args.output_root.resolve()
    runs_root = output_root / "runs"
    configs_root = output_root / "configs"
    logs_root = output_root / "logs"
    for p in (runs_root, configs_root, logs_root):
        p.mkdir(parents=True, exist_ok=True)

    master_rows = []
    failed_rows = []
    run_list = list(build_runs(args, base_config))

    print(f"[BATCH] output root: {output_root}")
    print(f"[BATCH] mode: {args.mode}")
    print(f"[BATCH] total runs: {len(run_list)}")
    print(f"[BATCH] P_wall values: {args.pwall_values}")
    print(f"[BATCH] Vmax values: {args.vmax_values}")
    print(f"[BATCH] inlet mmHg values: {args.inlet_mmhg_values}")
    print(f"[BATCH] solver: {args.solver.resolve()}")
    print(f"[BATCH] base config: {args.base_config.resolve()}")

    env = os.environ.copy()
    env["PYTHONIOENCODING"] = "utf-8"

    for i, (run_id, pwall, vmax, inlet) in enumerate(run_list, start=1):
        print(f"\n[{i}/{len(run_list)}] {run_id}")
        run_dir = runs_root / run_id
        run_dir.mkdir(parents=True, exist_ok=True)

        cfg = dict(base_config)
        cfg["P_wall"] = pwall
        cfg["Vmax"] = vmax
        cfg["inlet_mmHg"] = inlet
        cfg["inlet_concentration"] = None
        cfg["outdir"] = str(run_dir)
        cfg["label"] = run_id
        # Strongly recommended for oxygen maps without Hb artifacts.
        cfg.setdefault("Hb_capacity", 0.0)

        cfg_file = configs_root / f"{run_id}.json"
        write_json(cfg_file, cfg)
        # Save exact config inside the run directory too.
        write_json(run_dir / "config_used.json", cfg)

        stdout_file = logs_root / f"{run_id}.stdout.txt"
        stderr_file = logs_root / f"{run_id}.stderr.txt"
        cmd = [str(args.python), str(args.solver), "--config", str(cfg_file), "--outdir", str(run_dir)]

        with stdout_file.open("w", encoding="utf-8") as out, stderr_file.open("w", encoding="utf-8") as err:
            proc = subprocess.run(cmd, stdout=out, stderr=err, env=env)

        # Also copy logs into the run folder for self-contained inspection.
        try:
            (run_dir / "stdout.txt").write_text(stdout_file.read_text(encoding="utf-8", errors="replace"), encoding="utf-8")
            (run_dir / "stderr.txt").write_text(stderr_file.read_text(encoding="utf-8", errors="replace"), encoding="utf-8")
        except Exception:
            pass

        if proc.returncode != 0:
            row = {
                "run_id": run_id,
                "P_wall_m_s": pwall,
                "Vmax_mM_s": vmax,
                "inlet_mmHg": inlet,
                "returncode": proc.returncode,
                "run_dir": str(run_dir),
                "stderr_file": str(stderr_file),
            }
            failed_rows.append(row)
            print(f"[FAIL] return code {proc.returncode}. See {stderr_file}")
            if args.stop_on_fail:
                break
            continue

        summary_csv = run_dir / "oxygenation_summary.csv"
        if summary_csv.exists():
            df = pd.read_csv(summary_csv)
            df.insert(0, "run_id", run_id)
            if "outdir" in df.columns:
                df["outdir"] = f"runs/{run_id}"  # relative, so the table is portable
            master_rows.append(df.iloc[0].to_dict())
            print(f"[OK] saved: {run_dir}")
        else:
            failed_rows.append({
                "run_id": run_id,
                "P_wall_m_s": pwall,
                "Vmax_mM_s": vmax,
                "inlet_mmHg": inlet,
                "returncode": proc.returncode,
                "run_dir": str(run_dir),
                "stderr_file": str(stderr_file),
                "note": "Run completed but oxygenation_summary.csv was not found.",
            })
            print(f"[WARN] completed but missing oxygenation_summary.csv in {run_dir}")

        if master_rows:
            pd.DataFrame(master_rows).to_csv(output_root / "MASTER_oxygenation_summary.csv", index=False)
        if failed_rows:
            pd.DataFrame(failed_rows).to_csv(output_root / "MASTER_failed_runs.csv", index=False)

    if master_rows:
        master = pd.DataFrame(master_rows)
        master.to_csv(output_root / "MASTER_oxygenation_summary.csv", index=False)
        print(f"\n[DONE] master summary: {output_root / 'MASTER_oxygenation_summary.csv'}")
    else:
        print("\n[DONE] no successful runs were collected.")

    if failed_rows:
        pd.DataFrame(failed_rows).to_csv(output_root / "MASTER_failed_runs.csv", index=False)
        print(f"[DONE] failed runs: {output_root / 'MASTER_failed_runs.csv'}")

    print(f"[DONE] all individual run folders are under: {runs_root}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
